_DEFAULT_FAILLOCK_CONF = "/etc/security/faillock.conf"
_DEFAULT_PWQUALITY_CONF = "/etc/security/pwquality.conf"
_DEFAULT_LIMITS_CONF = "/etc/security/limits.conf"
_DEFAULT_LIMITS_DIR = "/etc/security/limits.d"
