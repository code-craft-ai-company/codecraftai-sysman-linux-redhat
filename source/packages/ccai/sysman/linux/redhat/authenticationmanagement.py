# ccai.sysman.linux.redhat.authenticationmanagement
#
# AuthenticationManager wraps the Red Hat Linux authentication stack
# through the ICommandRunner abstraction.  The surface covers:
#
#   - authselect profile + feature management
#   - direct PAM service-file reads / writes (with marker protection)
#   - /etc/security/pwquality.conf (pam_pwquality directives)
#   - /etc/security/faillock.conf and `faillock` per-user state
#   - /etc/security/limits.conf and /etc/security/limits.d/*
#   - /etc/nsswitch.conf source ordering
#
# Seams (intentional non-overlap with sibling features):
#   - 3-user-group-management owns local-account creation, password
#     expiry, and per-user SSH keys.
#   - 3-ssh-server-configuration owns sshd-level configuration.
#   - 3-identity-management owns directory-binding, realm joins, and
#     Kerberos ticketing.
#   - 3-security-compliance reads via this feature's query verbs but
#     does not mutate configuration here.
#
# All file I/O is routed through the runner using `cat` (read) and
# `tee` (write).  No direct filesystem access occurs in this module.

