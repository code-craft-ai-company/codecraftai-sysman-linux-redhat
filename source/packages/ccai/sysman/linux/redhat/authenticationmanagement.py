@dataclass
class AuthActionResult(FeatureActionResult):
    """
        Outcome of an authentication-management action.  Adds an
        optional ``subsystem`` field (PAM service name, ``authselect``
        feature, faillock directive, etc.) for traceability beyond the
        base ``detail`` string.
    """
    subsystem: Optional[str] = None


@dataclass
class AuthselectProfile:
    """
        Parsed result of ``authselect current``.

        :param id: Profile id (``sssd``, ``minimal``, ``winbind``, ...).
                   Empty string when no profile is currently active.
        :param features: List of enabled feature names.
        :param raw: The full ``authselect current`` stdout for
                    diagnostics / report attachment.
    """
    id: str
    features: list = field(default_factory=list)
    raw: str = ""


@dataclass
class FaillockState:
    """
        Per-user lockout state parsed from ``faillock --user <user>``.

        :param user: The user name queried.
        :param recent_failures: Count of valid failed-login records.
        :param locked: True when ``recent_failures`` is at or above
                       the live ``deny`` threshold from
                       ``/etc/security/faillock.conf``.
    """
    user: str
    recent_failures: int
    locked: bool


@dataclass
class LimitEntry:
    """
        A single line in ``/etc/security/limits.conf`` or any drop-in
        under ``/etc/security/limits.d/*``.

        :param domain: ``*`` (any user), ``@<group>``, or a username.
        :param limit_type: ``soft`` / ``hard`` / ``-`` (both).
        :param item: ``nofile``, ``nproc``, ``stack``, ``memlock``, ...
        :param value: The numeric or symbolic value, kept as a string
                      to preserve the user's original form.
        :param source_path: Absolute path to the file the entry was
                            parsed from.
    """
    domain: str
    limit_type: str
    item: str
    value: str
    source_path: str = ""


# ----------------------------------------------------------------------
# Exceptions
# ----------------------------------------------------------------------


class AuthselectOverrideError(SemanticError):
    """
        Raised when a caller attempts to overwrite a ``/etc/pam.d/``
        service file marked as ``# Generated by authselect`` without
        explicitly setting ``allow_overwrite_authselect=True``.
        Subclasses :class:`SemanticError` so it bubbles past every
        guarded block in the package.
    """

    def __init__(
        self,
        *,
        path: str,
        detail: str,
    ) -> None:
        """
            :param path: Absolute path of the protected service file.
            :param detail: Human-readable explanation.
        """
        self.path = path
        self.detail = detail

        err_msg_lines = ["Refusing to overwrite an authselect-managed PAM file."]
        err_msg_lines.append("    PATH:   {}".format(path))
        err_msg_lines.append("    DETAIL: {}".format(detail))
        err_msg = os.linesep.join(err_msg_lines)
        super().__init__(err_msg)
        return


