# Manager
# ----------------------------------------------------------------------


class AuthenticationManager(BaseFeatureManager):
    """
        Facade for Red Hat Linux authentication-stack management
        through the command runner.

        Uses :class:`BaseFeatureManager` plumbing for ``_dispatch``
        and dry-run handling.  Read verbs invoke the runner directly
        with ``elevated=False`` since reads under ``/etc/`` are
        world-readable on RHEL.
    """

    result_class = AuthActionResult
    status_class = AuthActionStatus
    feature_name = "authentication-management"

    # ------------------------------------------------------------------
    # authselect: profile + features
    # ------------------------------------------------------------------

    def current_profile(self) -> AuthselectProfile:
        """
            Query the active ``authselect`` profile.

            :returns: An :class:`AuthselectProfile` whose ``id`` is the
                      empty string when no profile is currently active
                      (i.e. ``authselect current`` reports failure).
        """
        command = [_AUTHSELECT, "current"]
        run_result = self._runner.run(list(command), elevated=False)
        if run_result.exit_code != 0:
            empty_profile = AuthselectProfile(
                id="", features=[], raw=run_result.stdout or "",
            )
            return empty_profile

        parsed = _parse_authselect_current(stdout=run_result.stdout)
        rtnval = AuthselectProfile(
            id=parsed["id"],
            features=parsed["features"],
            raw=run_result.stdout,
        )
        return rtnval

    def list_profiles(self) -> list:
        """
            Return the list of ``authselect`` profile ids available
            on the host.

            :returns: A ``list[str]`` of profile ids.  Returns an
                      empty list when ``authselect list`` fails
                      (e.g. authselect not installed).
        """
        command = [_AUTHSELECT, "list"]
        run_result = self._runner.run(list(command), elevated=False)
        if run_result.exit_code != 0:
            empty_list: list = []
            return empty_list

        rtnval = _parse_authselect_list(stdout=run_result.stdout)
        return rtnval

    def select_profile(
        self,
        profile: str,
        features: Optional[list] = None,
    ) -> AuthActionResult:
        """
            Select an ``authselect`` profile, optionally with feature
            flags.  The ``--force`` flag is always passed because
            switching from a hand-edited ``/etc/pam.d/`` requires it.

            :param profile: Target profile id.
            :param features: Optional list of feature flags to pass on
                             the ``authselect select`` command line.

            :returns: SKIPPED when the current profile id and feature
                      set already match the request.
        """
        if features is None:
            requested_features: list = []
        else:
            requested_features = list(features)

        current = self.current_profile()
        if current.id == profile:
            current_set = set(current.features)
            requested_set = set(requested_features)
            if current_set == requested_set:
                skipped = self._build_skipped(
                    detail=profile, subsystem="authselect",
                    command=_build_select_command(
                        profile=profile, features=requested_features,
                    ),
                )
                return skipped

        command = _build_select_command(
            profile=profile, features=requested_features,
        )
        rtnval = self._dispatch(
            command=command,
            detail=profile,
            operation="select_profile",
            subsystem="authselect",
        )
        return rtnval

    def enable_feature(
        self,
        feature: str,
        *,
        persist: bool = False,
    ) -> AuthActionResult:
        """
            Enable an ``authselect`` feature.

            :param feature: Feature name (e.g. ``with-sudo``,
                            ``with-faillock``).
            :param persist: When True, follow the toggle with
                            ``authselect apply-changes`` so the new
                            state is materialised under
                            ``/etc/pam.d/``.

            :returns: SKIPPED when the feature is already enabled.
        """
        current = self.current_profile()
        if feature in current.features:
            skipped = self._build_skipped(
                detail=feature, subsystem="authselect",
                command=[_AUTHSELECT, "enable-feature", feature],
            )
            return skipped

        command = [_AUTHSELECT, "enable-feature", feature]
        toggle_result = self._dispatch(
            command=command,
            detail=feature,
            operation="enable_feature",
            subsystem="authselect",
        )
        rtnval = self._maybe_apply_changes(
            toggle_result=toggle_result, persist=persist,
        )
        return rtnval

    def disable_feature(
        self,
        feature: str,
        *,
        persist: bool = False,
    ) -> AuthActionResult:
        """
            Disable an ``authselect`` feature.

            :param feature: Feature name.
            :param persist: When True, follow the toggle with
                            ``authselect apply-changes``.

            :returns: SKIPPED when the feature is already absent from
                      the active profile's feature set.
        """
        current = self.current_profile()
        if feature not in current.features:
            skipped = self._build_skipped(
                detail=feature, subsystem="authselect",
                command=[_AUTHSELECT, "disable-feature", feature],
            )
            return skipped

        command = [_AUTHSELECT, "disable-feature", feature]
        toggle_result = self._dispatch(
            command=command,
            detail=feature,
            operation="disable_feature",
            subsystem="authselect",
        )
        rtnval = self._maybe_apply_changes(
            toggle_result=toggle_result, persist=persist,
        )
        return rtnval

    def apply_changes(self) -> AuthActionResult:
        """
            Persist any pending ``authselect`` edits to ``/etc/pam.d/``.
            Dispatches ``authselect apply-changes``.
        """
        command = [_AUTHSELECT, "apply-changes"]
        rtnval = self._dispatch(
            command=command,
            detail="apply-changes",
            operation="apply_changes",
            subsystem="authselect",
        )
        return rtnval

    # ------------------------------------------------------------------
    # PAM service-file drop-ins
    # ------------------------------------------------------------------

    def read_service(self, service: str) -> str:
        """
            Read ``/etc/pam.d/<service>`` via ``cat``.

            :param service: Service name (basename of the PAM service
                            file).

            :returns: The raw file content; an empty string when the
                      file does not exist or the read fails.
        """
        path = self._pam_service_path(service=service)
        rtnval = self._read_file(path=path)
        return rtnval

    def write_service(
        self,
        service: str,
        content: str,
        *,
        allow_overwrite_authselect: bool = False,
    ) -> AuthActionResult:
        """
            Idempotently write ``/etc/pam.d/<service>``.

            Refuses to clobber an authselect-managed file unless the
            caller explicitly opts in.

            :param service: PAM service-file basename.
            :param content: Desired full file content.
            :param allow_overwrite_authselect: Set True to permit
                                               overwriting a file
                                               whose first comment
                                               line carries the
                                               authselect marker.

            :returns: SKIPPED on identical content; otherwise the
                      result of dispatching the ``tee`` write.
            :raises AuthselectOverrideError:
                When the existing file is authselect-managed and
                ``allow_overwrite_authselect`` is False.
        """
        path = self._pam_service_path(service=service)
        existing = self._read_file(path=path)

        if existing == content:
            skipped = self._build_skipped(
                detail=path, subsystem=service,
                command=[_TEE, path],
            )
            return skipped

        if _has_authselect_marker(content=existing):
            if not allow_overwrite_authselect:
                raise AuthselectOverrideError(
                    path=path,
                    detail=(
                        "Pass allow_overwrite_authselect=True to "
                        "explicitly clobber the managed file."
                    ),
                )

        rtnval = self._dispatch(
            command=[_TEE, path],
            detail=path,
            stdin=content,
            operation="write_service",
            subsystem=service,
        )
        return rtnval

    def write_dropin(
        self,
        service: str,
        name: str,
        content: str,
    ) -> AuthActionResult:
        """
            Write a PAM drop-in at ``/etc/pam.d/<service>.d/<name>``.

            Ensures the parent drop-in directory exists by issuing
            ``mkdir -p`` first.  The ``mkdir`` command honours the
            same dry-run / elevation policy as the ``tee`` write.

            :param service: PAM service-file basename.
            :param name: Drop-in file basename.
            :param content: Desired full file content.

            :returns: SKIPPED on identical content; otherwise the
                      result of the ``tee`` write.
        """
        dropin_dir = "{}/{}.d".format(self._typed_config().pam_dir, service)
        dropin_path = "{}/{}".format(dropin_dir, name)

        existing = self._read_file(path=dropin_path)
        if existing == content:
            skipped = self._build_skipped(
                detail=dropin_path, subsystem=service,
                command=[_TEE, dropin_path],
            )
            return skipped

        mkdir_command = [_MKDIR, "-p", dropin_dir]
        mkdir_result = self._dispatch(
            command=mkdir_command,
            detail=dropin_dir,
            operation="write_dropin_mkdir",
            subsystem=service,
        )
        if mkdir_result.status == self.status_class.FAILED:
            return mkdir_result

        rtnval = self._dispatch(
            command=[_TEE, dropin_path],
            detail=dropin_path,
            stdin=content,
            operation="write_dropin",
            subsystem=service,
        )
        return rtnval

    # ------------------------------------------------------------------
    # pam_pwquality
    # ------------------------------------------------------------------

    def get_pwquality(self) -> dict:
        """
            Parse ``/etc/security/pwquality.conf`` into a
            ``dict[str, str]``.  Comment lines and blank lines are
            ignored.  Returns an empty dict when the file is missing.
        """
        path = self._typed_config().pwquality_conf
        text = self._read_file(path=path)
        rtnval = _parse_keyvalue_conf(text=text)
        return rtnval

    def set_pwquality_directive(
        self,
        key: str,
        value: str,
    ) -> AuthActionResult:
        """
            Upsert ``<key> = <value>`` in
            ``/etc/security/pwquality.conf``.  SKIPPED when the
            current value already matches.
        """
        path = self._typed_config().pwquality_conf
        existing_text = self._read_file(path=path)
        existing_kv = _parse_keyvalue_conf(text=existing_text)

        if existing_kv.get(key) == value:
            skipped = self._build_skipped(
                detail="{}={}".format(key, value), subsystem="pwquality",
                command=[_TEE, path],
            )
            return skipped

        new_text = _upsert_keyvalue_line(
            text=existing_text, key=key, value=value,
        )
        rtnval = self._dispatch(
            command=[_TEE, path],
            detail="{}={}".format(key, value),
            stdin=new_text,
            operation="set_pwquality_directive",
            subsystem="pwquality",
        )
        return rtnval

    def remove_pwquality_directive(self, key: str) -> AuthActionResult:
        """
            Strip the ``<key> = ...`` line from
            ``/etc/security/pwquality.conf``.  SKIPPED when the
            directive is already absent.
        """
        path = self._typed_config().pwquality_conf
        existing_text = self._read_file(path=path)
        existing_kv = _parse_keyvalue_conf(text=existing_text)

        if key not in existing_kv:
            skipped = self._build_skipped(
                detail=key, subsystem="pwquality",
                command=[_TEE, path],
            )
            return skipped

        new_text = _remove_keyvalue_line(text=existing_text, key=key)
        rtnval = self._dispatch(
            command=[_TEE, path],
            detail=key,
            stdin=new_text,
            operation="remove_pwquality_directive",
            subsystem="pwquality",
        )
        return rtnval

