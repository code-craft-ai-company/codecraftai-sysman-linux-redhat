    faillock_conf: str = _DEFAULT_FAILLOCK_CONF
    pwquality_conf: str = _DEFAULT_PWQUALITY_CONF
    limits_conf: str = _DEFAULT_LIMITS_CONF
    limits_dir: str = _DEFAULT_LIMITS_DIR
    nsswitch_conf: str = _DEFAULT_NSSWITCH_CONF
    pam_dir: str = _DEFAULT_PAM_DIR


