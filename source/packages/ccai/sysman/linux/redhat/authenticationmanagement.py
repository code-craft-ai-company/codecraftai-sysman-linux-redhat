    def get_faillock_state(self, user: str) -> FaillockState:
        """
            Query a user's lockout state via ``faillock --user
            <user>``.

            :param user: The user name.

            :returns: A :class:`FaillockState`.  ``recent_failures``
                      is the count of valid (V) failure rows;
                      ``locked`` is True when that count meets or
                      exceeds the live ``deny`` value from
                      ``faillock.conf`` (defaults to 3 when not
                      configured).
        """
        command = [_FAILLOCK, "--user", user]
        run_result = self._runner.run(list(command), elevated=False)
        if run_result.exit_code != 0:
            failed_state = FaillockState(
                user=user, recent_failures=0, locked=False,
            )
            return failed_state

        recent_failures = _count_faillock_valid_rows(
            stdout=run_result.stdout,
        )

        live_kv = self.get_faillock()
        deny_text = live_kv.get("deny")
        if deny_text is None:
            deny_threshold = _DEFAULT_DENY_THRESHOLD
        else:
            deny_threshold = _safe_parse_int(
                text=deny_text, default=_DEFAULT_DENY_THRESHOLD,
            )

        is_locked = recent_failures >= deny_threshold
        rtnval = FaillockState(
            user=user,
            recent_failures=recent_failures,
            locked=is_locked,
        )
        return rtnval

    def reset_faillock(self, user: str) -> AuthActionResult:
        """
            Reset a user's failed-login counter via ``faillock --user
            <user> --reset``.
        """
        command = [_FAILLOCK, "--user", user, "--reset"]
        rtnval = self._dispatch(
            command=command,
            detail=user,
            operation="reset_faillock",
            subsystem="faillock",
        )
        return rtnval

    # ------------------------------------------------------------------
    # /etc/security/limits.*
    # ------------------------------------------------------------------

    def get_limits(self) -> list:
        """
            Aggregate ``/etc/security/limits.conf`` and every file
            under ``/etc/security/limits.d/`` into a
            ``list[LimitEntry]``.

            Drop-in files are listed via ``ls -1`` then read via
            ``cat``.  When ``ls`` fails the master file is still
            included.
        """
        rtnval: list = []

        master_path = self._typed_config().limits_conf
        master_text = self._read_file(path=master_path)
        if len(master_text) > 0:
            master_entries = _parse_limits_text(
                text=master_text, source_path=master_path,
            )
            rtnval.extend(master_entries)

        limits_dir = self._typed_config().limits_dir
        ls_command = ["ls", "-1", limits_dir]
        ls_result = self._runner.run(list(ls_command), elevated=False)
        if ls_result.exit_code != 0:
            return rtnval

        for raw_name in ls_result.stdout.splitlines():
            stripped = raw_name.strip()
            if len(stripped) == 0:
                continue
            file_path = "{}/{}".format(limits_dir, stripped)
            file_text = self._read_file(path=file_path)
            file_entries = _parse_limits_text(
                text=file_text, source_path=file_path,
            )
            rtnval.extend(file_entries)
        return rtnval

    def set_limit(
        self,
        entry: LimitEntry,
        drop_in: str,
    ) -> AuthActionResult:
        """
            Upsert a limits-line in
            ``/etc/security/limits.d/<drop_in>.conf``.  Matching is by
            ``(domain, limit_type, item)``.  SKIPPED when an existing
            entry already carries the same value.
        """
        path = self._dropin_limits_path(drop_in=drop_in)
        existing_text = self._read_file(path=path)

        existing_entries = _parse_limits_text(
            text=existing_text, source_path=path,
        )
        for existing in existing_entries:
            same_key = (
                existing.domain == entry.domain
                and existing.limit_type == entry.limit_type
                and existing.item == entry.item
            )
            if same_key and existing.value == entry.value:
                skipped = self._build_skipped(
                    detail=_render_limit_line(entry=entry),
                    subsystem="limits",
                    command=[_TEE, path],
                )
                return skipped

        new_text = _upsert_limit_line(
            text=existing_text, entry=entry,
        )
        rtnval = self._dispatch(
            command=[_TEE, path],
            detail=_render_limit_line(entry=entry),
            stdin=new_text,
            operation="set_limit",
            subsystem="limits",
        )
        return rtnval

    def remove_limit(
        self,
        entry: LimitEntry,
        drop_in: str,
    ) -> AuthActionResult:
        """
            Strip a limits-line from
            ``/etc/security/limits.d/<drop_in>.conf``.  When the file
            becomes empty (no non-blank, non-comment lines) THE FILE
            IS REMOVED via ``rm -f``.
        """
        path = self._dropin_limits_path(drop_in=drop_in)
        existing_text = self._read_file(path=path)

        existing_entries = _parse_limits_text(
            text=existing_text, source_path=path,
        )
        match_found = False
        for existing in existing_entries:
            same_key = (
                existing.domain == entry.domain
                and existing.limit_type == entry.limit_type
                and existing.item == entry.item
            )
            if same_key:
                match_found = True
                break

        if not match_found:
            skipped = self._build_skipped(
                detail=_render_limit_line(entry=entry),
                subsystem="limits",
                command=[_TEE, path],
            )
            return skipped

        new_text = _remove_limit_line(text=existing_text, entry=entry)
        if _is_blank_or_comments_only(text=new_text):
            rm_command = [_RM, "-f", path]
            rtnval = self._dispatch(
                command=rm_command,
                detail=path,
                operation="remove_limit_rm",
                subsystem="limits",
            )
            return rtnval

        rtnval = self._dispatch(
            command=[_TEE, path],
            detail=_render_limit_line(entry=entry),
            stdin=new_text,
            operation="remove_limit",
            subsystem="limits",
        )
        return rtnval

    # ------------------------------------------------------------------
    # /etc/nsswitch.conf
    # ------------------------------------------------------------------

    def get_nss_sources(self) -> dict:
        """
            Parse ``/etc/nsswitch.conf`` into a
            ``dict[str, list[str]]`` keyed by database name.  Comment
            lines and blank lines are ignored.
        """
        path = self._typed_config().nsswitch_conf
        text = self._read_file(path=path)
        rtnval = _parse_nsswitch_text(text=text)
        return rtnval

    def set_nss_sources(
        self,
        db: str,
        sources: list,
    ) -> AuthActionResult:
        """
            Replace the source ordering of ``<db>`` in
            ``/etc/nsswitch.conf``.  All other lines are preserved
            verbatim, including trailing comments.

            SKIPPED when the requested ordering already matches the
            file.
        """
        path = self._typed_config().nsswitch_conf
        existing_text = self._read_file(path=path)
        existing_dbs = _parse_nsswitch_text(text=existing_text)

        requested_sources = list(sources)
        if existing_dbs.get(db) == requested_sources:
            skipped = self._build_skipped(
                detail="{}: {}".format(db, " ".join(requested_sources)),
                subsystem="nsswitch",
                command=[_TEE, path],
            )
            return skipped

        new_text = _upsert_nsswitch_db(
            text=existing_text, db=db, sources=requested_sources,
        )
        rtnval = self._dispatch(
            command=[_TEE, path],
            detail="{}: {}".format(db, " ".join(requested_sources)),
            stdin=new_text,
            operation="set_nss_sources",
            subsystem="nsswitch",
        )
        return rtnval

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    def _typed_config(self) -> AuthenticationManagerConfig:
        """
            Return the active config narrowed to
            :class:`AuthenticationManagerConfig`.  Constructs a fresh
            instance from the base config when a non-typed config was
            injected.
        """
        if isinstance(self._config, AuthenticationManagerConfig):
            rtnval = self._config
        else:
            rtnval = AuthenticationManagerConfig(
                dry_run=self._config.dry_run,
                elevated=self._config.elevated,
            )
        return rtnval

    def _pam_service_path(self, *, service: str) -> str:
        """
            Compose the absolute PAM service-file path.
        """
        rtnval = "{}/{}".format(self._typed_config().pam_dir, service)
        return rtnval

    def _dropin_limits_path(self, *, drop_in: str) -> str:
        """
            Compose the absolute path to a limits.d drop-in file,
            appending the ``.conf`` suffix when not already present.
        """
        limits_dir = self._typed_config().limits_dir
        if drop_in.endswith(".conf"):
            file_name = drop_in
        else:
            file_name = "{}.conf".format(drop_in)
        rtnval = "{}/{}".format(limits_dir, file_name)
        return rtnval

    def _read_file(self, *, path: str) -> str:
        """
            Read a file via ``cat``.  Returns empty string on any
            non-zero exit (treats "missing file" the same as "empty
            file" for upsert idempotency).
        """
        run_result = self._runner.run(
            [_CAT, path], elevated=False,
        )
        if run_result.exit_code != 0:
            empty: str = ""
            return empty
        rtnval = run_result.stdout
        return rtnval

    def _build_skipped(
        self,
        *,
        detail: Optional[str],
        subsystem: Optional[str],
        command: list,
    ) -> AuthActionResult:
        """
            Construct an AuthActionResult with status SKIPPED without
            invoking the runner.
        """
        rtnval = AuthActionResult(
            status=self.status_class.SKIPPED,
            detail=detail,
            command=list(command),
            subsystem=subsystem,
        )
        return rtnval

    def _maybe_apply_changes(
        self,
        *,
        toggle_result: AuthActionResult,
        persist: bool,
    ) -> AuthActionResult:
        """
            When ``persist`` is True and the preceding toggle did not
            FAIL, dispatch ``authselect apply-changes``.

            :returns: The toggle result when ``persist`` is False or
                      the toggle FAILED; otherwise the apply-changes
                      result.
        """
        if not persist:
            return toggle_result
        if toggle_result.status == self.status_class.FAILED:
            return toggle_result
        if toggle_result.status == self.status_class.DRY_RUN:
            return toggle_result

        rtnval = self.apply_changes()
        return rtnval


