def _parse_authselect_current(*, stdout: str) -> dict:
    """
        Parse the ``authselect current`` output into a dict carrying
        ``id`` and ``features``.

        Expected shape::

            Profile ID: sssd
            Enabled features:
            - with-sudo
            - with-mkhomedir

        Empty / no-profile output is mapped to ``id=""``,
        ``features=[]``.

        :param stdout: The raw stdout from ``authselect current``.

        :returns: ``{"id": str, "features": list[str]}``.
    """
    profile_id = ""
    features: list = []
    in_features = False

    for raw_line in stdout.splitlines():
        line = raw_line.rstrip()
        stripped = line.strip()
        if len(stripped) == 0:
            continue

        lower = stripped.lower()
        if lower.startswith("profile id"):
            _, _, value = stripped.partition(":")
            profile_id = value.strip()
            in_features = False
            continue

        if lower.startswith("enabled features"):
            in_features = True
            continue

        if in_features:
            if stripped.startswith("- "):
                feature = stripped[2:].strip()
            elif stripped.startswith("-"):
                feature = stripped[1:].strip()
            else:
                feature = stripped
            if len(feature) > 0:
                features.append(feature)

    rtnval = {"id": profile_id, "features": features}
    return rtnval


def _parse_authselect_list(*, stdout: str) -> list:
    """
        Parse ``authselect list`` output into a list of profile ids.

        Expected shape::

            - minimal      Local users only for minimal installs
            - nis          Enable NIS for system authentication
            - sssd         Enable SSSD for system authentication
            - winbind      Enable winbind for system authentication

        :param stdout: The raw stdout.

        :returns: A ``list[str]`` of profile ids in declaration order.
    """
    rtnval: list = []
    for raw_line in stdout.splitlines():
        stripped = raw_line.strip()
        if len(stripped) == 0:
            continue
        if stripped.startswith("-"):
            body = stripped[1:].strip()
        else:
            body = stripped
        tokens = body.split()
        if len(tokens) == 0:
            continue
        first_token = tokens[0]
        if len(first_token) > 0:
            rtnval.append(first_token)
    return rtnval


def _build_select_command(*, profile: str, features: list) -> list:
    """
        Compose the ``authselect select`` argv with ``--force`` and
        the optional list of feature flags.
    """
    rtnval = [_AUTHSELECT, "select", profile]
    for feature in features:
        rtnval.append(feature)
    rtnval.append("--force")
    return rtnval


def _has_authselect_marker(*, content: str) -> bool:
    """
        Return True when the first non-blank line of ``content``
        carries the authselect-managed marker.
    """
    for raw_line in content.splitlines():
        stripped = raw_line.strip()
        if len(stripped) == 0:
            continue
        if stripped.startswith(_AUTHSELECT_MARKER):
            rtnval = True
            return rtnval
        # Only inspect the first non-blank line.
        rtnval = False
        return rtnval
    rtnval = False
    return rtnval


def _parse_keyvalue_conf(*, text: str) -> dict:
    """
        Parse a flat ``key = value`` config file into a dict.  Lines
        starting with ``#`` and blank lines are ignored.  Splits on
        the first ``=`` only; both ``key=value`` and ``key = value``
        are accepted.
    """
    rtnval: dict = {}
    for raw_line in text.splitlines():
        stripped = raw_line.strip()
        if len(stripped) == 0:
            continue
        if stripped.startswith("#"):
            continue
        if "=" not in stripped:
            # A bare keyword line (e.g. faillock's "even_deny_root").
            rtnval[stripped] = ""
            continue
        key_part, _, value_part = stripped.partition("=")
        key_text = key_part.strip()
        value_text = value_part.strip()
        if len(key_text) == 0:
            continue
        rtnval[key_text] = value_text
    return rtnval


def _upsert_keyvalue_line(
    *,
    text: str,
    key: str,
    value: str,
) -> str:
    """
        Return ``text`` with ``<key> = <value>`` upserted.  Preserves
        every line that does not match ``<key>(=|<space>)``.
    """
    new_line = "{} = {}".format(key, value)
    lines: list = []
    found = False

    for raw_line in text.splitlines():
        stripped = raw_line.strip()
        if stripped.startswith("#") or len(stripped) == 0:
            lines.append(raw_line)
            continue
        if "=" in stripped:
            key_part, _, _ = stripped.partition("=")
            if key_part.strip() == key:
                lines.append(new_line)
                found = True
                continue
        else:
            if stripped == key:
                lines.append(new_line)
                found = True
                continue
        lines.append(raw_line)

    if not found:
        lines.append(new_line)

    body = "\n".join(lines)
    if not body.endswith("\n"):
        body = body + "\n"
    return body


def _remove_keyvalue_line(*, text: str, key: str) -> str:
    """
        Return ``text`` with the matching ``<key> = ...`` line stripped.
    """
    lines: list = []
    for raw_line in text.splitlines():
        stripped = raw_line.strip()
        if stripped.startswith("#") or len(stripped) == 0:
            lines.append(raw_line)
            continue
        if "=" in stripped:
            key_part, _, _ = stripped.partition("=")
            if key_part.strip() == key:
                continue
        else:
            if stripped == key:
                continue
        lines.append(raw_line)
    body = "\n".join(lines)
    if len(body) > 0 and not body.endswith("\n"):
        body = body + "\n"
    return body


def _count_faillock_valid_rows(*, stdout: str) -> int:
    """
        Count rows in ``faillock --user`` output whose ``Valid``
        column is ``V``.

        Expected row shape (whitespace-separated)::

            When                Type  Source                 Valid
            2025-04-27 09:01:11 RHOST 198.51.100.4              V

        Header rows are skipped by detecting the literal "When"
        keyword in the first column.
    """
    count = 0
    for raw_line in stdout.splitlines():
        stripped = raw_line.strip()
        if len(stripped) == 0:
            continue
        tokens = stripped.split()
        if len(tokens) == 0:
            continue
        # Skip headers and the "user:" preamble.
        first_token = tokens[0]
        if first_token == "When":
            continue
        if first_token.endswith(":"):
            continue
        last_token = tokens[-1]
        if last_token == "V":
            count += 1
    return count


def _safe_parse_int(*, text: str, default: int) -> int:
    """
        Parse an integer from ``text``, returning ``default`` when
        parsing fails.  Tolerates leading / trailing whitespace.
    """
    candidate = text.strip()
    if len(candidate) == 0:
        return default
    try:
        rtnval = int(candidate)
        return rtnval
    except ValueError:
        return default


def _parse_limits_text(*, text: str, source_path: str) -> list:
    """
        Parse ``/etc/security/limits.conf`` (or a drop-in) into a
        ``list[LimitEntry]``.  Comment lines and blank lines are
        skipped.  Malformed lines (fewer than four tokens) are also
        skipped.
    """
    rtnval: list = []
    for raw_line in text.splitlines():
        stripped = raw_line.strip()
        if len(stripped) == 0:
            continue
        if stripped.startswith("#"):
            continue
        tokens = stripped.split()
        if len(tokens) < 4:
            continue
        domain = tokens[0]
        limit_type = tokens[1]
        item = tokens[2]
        value = tokens[3]
        entry = LimitEntry(
            domain=domain,
            limit_type=limit_type,
            item=item,
            value=value,
            source_path=source_path,
        )
        rtnval.append(entry)
    return rtnval


def _render_limit_line(*, entry: LimitEntry) -> str:
    """
        Render a :class:`LimitEntry` into a single
        ``<domain> <type> <item> <value>`` line.
    """
    rtnval = "{} {} {} {}".format(
        entry.domain, entry.limit_type, entry.item, entry.value,
    )
    return rtnval


def _upsert_limit_line(*, text: str, entry: LimitEntry) -> str:
    """
        Return ``text`` with ``entry`` upserted.  Match key is
        ``(domain, limit_type, item)``.  Preserves every other line.
    """
    target_line = _render_limit_line(entry=entry)
    lines: list = []
    found = False

    for raw_line in text.splitlines():
        stripped = raw_line.strip()
        if stripped.startswith("#") or len(stripped) == 0:
            lines.append(raw_line)
            continue
        tokens = stripped.split()
        if len(tokens) >= 4:
            if (
                tokens[0] == entry.domain
                and tokens[1] == entry.limit_type
                and tokens[2] == entry.item
            ):
                lines.append(target_line)
                found = True
                continue
        lines.append(raw_line)

    if not found:
        lines.append(target_line)

    body = "\n".join(lines)
    if not body.endswith("\n"):
        body = body + "\n"
    return body


def _remove_limit_line(*, text: str, entry: LimitEntry) -> str:
    """
        Return ``text`` with the line matching ``entry`` (by
        ``domain + type + item``) stripped.
    """
    lines: list = []
    for raw_line in text.splitlines():
        stripped = raw_line.strip()
        if stripped.startswith("#") or len(stripped) == 0:
            lines.append(raw_line)
            continue
        tokens = stripped.split()
        if len(tokens) >= 4:
            if (
                tokens[0] == entry.domain
                and tokens[1] == entry.limit_type
                and tokens[2] == entry.item
            ):
                continue
        lines.append(raw_line)

    body = "\n".join(lines)
    if len(body) > 0 and not body.endswith("\n"):
        body = body + "\n"
    return body


def _is_blank_or_comments_only(*, text: str) -> bool:
    """
        Return True when ``text`` contains no non-blank, non-comment
        lines.
    """
    for raw_line in text.splitlines():
        stripped = raw_line.strip()
        if len(stripped) == 0:
            continue
        if stripped.startswith("#"):
            continue
        rtnval = False
        return rtnval
    rtnval = True
    return rtnval


def _parse_nsswitch_text(*, text: str) -> dict:
    """
        Parse ``/etc/nsswitch.conf`` into ``dict[str, list[str]]``
        keyed by database.  Trailing comments are stripped from the
        source list.
    """
    rtnval: dict = {}
    for raw_line in text.splitlines():
        stripped = raw_line.strip()
        if len(stripped) == 0:
            continue
        if stripped.startswith("#"):
            continue
        if ":" not in stripped:
            continue

        # Strip trailing comment.
        comment_pos = stripped.find("#")
        if comment_pos >= 0:
            payload = stripped[:comment_pos].strip()
        else:
            payload = stripped

        db_part, _, sources_part = payload.partition(":")
        db_name = db_part.strip()
        if len(db_name) == 0:
            continue
        source_tokens = sources_part.split()
        rtnval[db_name] = source_tokens
    return rtnval


def _upsert_nsswitch_db(
    *,
    text: str,
    db: str,
    sources: list,
) -> str:
    """
        Replace the matching database line in ``text`` with
        ``<db>: <sources...>``.  Preserves every other line including
        comments.  When the database is not present the new line is
        appended to the end of the file.
    """
    new_line = "{}: {}".format(db, " ".join(sources))
    lines: list = []
    found = False

    for raw_line in text.splitlines():
        stripped = raw_line.strip()
        if stripped.startswith("#") or len(stripped) == 0:
            lines.append(raw_line)
            continue
        if ":" not in stripped:
            lines.append(raw_line)
            continue

        db_part, _, _ = stripped.partition(":")
        if db_part.strip() == db:
            lines.append(new_line)
            found = True
            continue
        lines.append(raw_line)

    if not found:
        lines.append(new_line)

    body = "\n".join(lines)
    if not body.endswith("\n"):
        body = body + "\n"
    return body
