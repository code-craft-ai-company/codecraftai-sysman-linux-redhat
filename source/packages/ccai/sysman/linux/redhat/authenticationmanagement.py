class AuthActionStatus(Enum):
    """
        Outcome status for every authentication-management write
        operation.  Mirrors the package-wide
        :class:`ccai.sysman.linux.redhat.featurebase.ActionStatus`
        enum so existing :class:`BaseFeatureManager` plumbing accepts
        it transparently.
    """
    SUCCESS = "success"
    FAILED = "failed"
    SKIPPED = "skipped"
    DRY_RUN = "dry_run"


