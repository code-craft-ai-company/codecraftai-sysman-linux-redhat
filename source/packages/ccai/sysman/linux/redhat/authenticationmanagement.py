    # pam_faillock
    # ------------------------------------------------------------------

    def get_faillock(self) -> dict:
        """
            Parse ``/etc/security/faillock.conf`` into a
            ``dict[str, str]``.  Empty dict when the file is missing.
        """
        path = self._typed_config().faillock_conf
        text = self._read_file(path=path)
        rtnval = _parse_keyvalue_conf(text=text)
        return rtnval

    def set_faillock_directive(
        self,
        key: str,
        value: str,
    ) -> AuthActionResult:
        """
            Upsert a directive in ``/etc/security/faillock.conf``.

            For ``even_deny_root``, the returned ``AuthActionResult``
            carries an explicit risk flag in ``detail`` so reports
            highlight the change.
        """
        path = self._typed_config().faillock_conf
        existing_text = self._read_file(path=path)
        existing_kv = _parse_keyvalue_conf(text=existing_text)

        detail_text = "{}={}".format(key, value)
        if key == "even_deny_root":
            detail_text = (
                "{} (RISK: lockout policy now applies to root)".format(
                    detail_text,
                )
            )

        if existing_kv.get(key) == value:
            skipped = self._build_skipped(
                detail=detail_text, subsystem="faillock",
                command=[_TEE, path],
            )
            return skipped

        new_text = _upsert_keyvalue_line(
            text=existing_text, key=key, value=value,
        )
        rtnval = self._dispatch(
            command=[_TEE, path],
            detail=detail_text,
            stdin=new_text,
            operation="set_faillock_directive",
            subsystem="faillock",
        )
        return rtnval

